/** Adding an authenticator through the real enrollFactor, with Supabase answering this QR code. */
function supabaseEnrolls(qrCode: string) {
  const { enrollFactor: realEnroll } = jest.requireActual<typeof import('@/api/owner')>('@/api/owner');
  jest.mocked(enrollFactor).mockImplementation(realEnroll);
  Object.assign(supabase, {
    auth: {
      mfa: {
        listFactors: jest.fn().mockResolvedValue({ data: { all: [], totp: [], phone: [] }, error: null }),
        enroll: jest.fn().mockResolvedValue({
          // supabase-js hands the markup back as a data: URL.
          data: { id: 'f1', type: 'totp', totp: { qr_code: `data:image/svg+xml;utf-8,${qrCode}`, secret: 'JBSWY3DPEHPK3PXP', uri: 'otpauth://totp/Jonz:owner?secret=JBSWY3DPEHPK3PXP' } },
          error: null,
        }),
      },
    },
  });
}

